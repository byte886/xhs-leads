// 登录失效判定（R-6.21f 用户拍板收窄）：仅**明确要求重新认证/登录**的信号才触发
// 登录引导（弹 APP 强制登录对话框）：
//   被踢 / 登录超限 / 重新登录 / 请登录 / 登录失效 / 登录态失效 / 登录已过期 /
//   需要验证登录 等——平台明示「会话已失效、需要重新登录」。
// **不触发**（功能限制，失败提示展示 detail，用户自行决策）：
//   - 风控/频率限制（「触发平台风险拦截，建议停用 ≥24h」「操作过于频繁」）——重登不解决；
//   - 违规/发布被拦（「发布被平台拦截（验证码/频繁/拦截）」「风控熔断」）——发布受限非登录失效；
//   - 提示性文案（「请确认 Chrome 已登录小红书且笔记可正常访问」）——告知状态，用户自会处理。
// 因此**不匹配裸「登录」「验证码」**：裸词会误伤上述功能限制类错误。
// 历史实测（audit risk_manual 日志）：真实风控验证文案「登录后查看（Cookie 有效
// 但被小红书风控拦截，需人工扫码/验证后重试）」——「需人工扫码/验证后重试」即
// 用户口径的「需要验证的类似说法」→ 触发登录引导（用户需扫码验证），已补词覆盖。
const RE_AUTH = /重新登录|请登录|登录失效|登录态|被踢|登录超限|登录已过期|需要验证|验证登录|需人工扫码|扫码验证|验证后重试/

export function isLoginAbnormal(msg: string | null | undefined): boolean {
  if (!msg) return false
  return RE_AUTH.test(msg)
}
